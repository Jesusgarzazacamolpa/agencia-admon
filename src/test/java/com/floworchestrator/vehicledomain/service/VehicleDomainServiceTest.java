package com.floworchestrator.vehicledomain.service;

import com.floworchestrator.vehicledomain.entity.PaymentMethod;
import com.floworchestrator.vehicledomain.entity.PurchaseOrder;
import com.floworchestrator.vehicledomain.entity.Vehicle;
import com.floworchestrator.vehicledomain.repository.PaymentMethodRepository;
import com.floworchestrator.vehicledomain.repository.PurchaseOrderRepository;
import com.floworchestrator.vehicledomain.repository.VehicleRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;

import java.math.BigDecimal;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

@ExtendWith(MockitoExtension.class)
class VehicleDomainServiceTest {

    @Mock
    private VehicleRepository vehicleRepository;
    @Mock
    private PurchaseOrderRepository purchaseOrderRepository;
    @Mock
    private PaymentMethodRepository paymentMethodRepository;

    private VehicleDomainService service;

    @BeforeEach
    void setUp() {
        service = new VehicleDomainService(vehicleRepository, purchaseOrderRepository, paymentMethodRepository);
    }

    @Test
    void shouldReturnVehicleMapWhenVehicleExists() {
        Vehicle vehicle = new Vehicle();
        vehicle.setVehicleId("V-001");
        vehicle.setModelId("M-001");
        vehicle.setBrand("Toyota");
        vehicle.setModel("Corolla");
        vehicle.setPrice(new BigDecimal("28900.00"));
        vehicle.setCurrency("MXN");
        vehicle.setAvailable(true);

        when(vehicleRepository.findByVehicleId("V-001")).thenReturn(Optional.of(vehicle));

        Map<String, Object> result = service.getVehicleById("V-001");

        assertThat(result).containsEntry("vehicle_id", "V-001");
        assertThat(result).containsEntry("model_id", "M-001");
        assertThat(result).containsEntry("brand", "Toyota");
        assertThat(result).containsEntry("model", "Corolla");
        assertThat(result).containsEntry("price", new BigDecimal("28900.00"));
        assertThat(result).containsEntry("currency", "MXN");
        assertThat(result).containsEntry("available", true);
    }

    @Test
    void shouldThrowNotFoundWhenVehicleDoesNotExist() {
        when(vehicleRepository.findByVehicleId("unknown")).thenReturn(Optional.empty());

        assertThatThrownBy(() -> service.getVehicleById("unknown"))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.NOT_FOUND));
    }

    @Test
    void shouldCreatePurchaseOrderWithAutoGeneratedId() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("vehicle_id", "V-001");
        payload.put("customer_id", "customer-007");

        Map<String, Object> response = service.createPurchaseOrder(payload);

        ArgumentCaptor<PurchaseOrder> captor = ArgumentCaptor.forClass(PurchaseOrder.class);
        verify(purchaseOrderRepository).save(captor.capture());
        PurchaseOrder saved = captor.getValue();

        assertThat(saved.getPurchaseOrderId()).startsWith("po-");
        assertThat(saved.getCustomerId()).isEqualTo("customer-007");
        assertThat(saved.getVehicleId()).isEqualTo("V-001");
        assertThat(saved.getStatus()).isEqualTo("CREATED");

        assertThat(response).containsEntry("status", "CREATED");
        assertThat(response).containsEntry("message", "Orden registrada correctamente");
        assertThat(response.get("purchase_order_id")).isEqualTo(saved.getPurchaseOrderId());
    }

    @Test
    void shouldCreatePurchaseOrderWithProvidedId() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("purchase_order_id", "po-custom-001");
        payload.put("customer_id", "customer-007");
        payload.put("vehicle_id", "V-999");

        Map<String, Object> response = service.createPurchaseOrder(payload);

        ArgumentCaptor<PurchaseOrder> captor = ArgumentCaptor.forClass(PurchaseOrder.class);
        verify(purchaseOrderRepository).save(captor.capture());
        PurchaseOrder saved = captor.getValue();

        assertThat(saved.getPurchaseOrderId()).isEqualTo("po-custom-001");
        assertThat(saved.getCustomerId()).isEqualTo("customer-007");
        assertThat(saved.getVehicleId()).isEqualTo("V-999");

        assertThat(response).containsEntry("purchase_order_id", "po-custom-001");
    }

    @Test
    void shouldThrowBadRequestWhenVehicleIdMissing() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("customer_id", "customer-007");

        assertThatThrownBy(() -> service.createPurchaseOrder(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldThrowBadRequestWhenCustomerIdMissing() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("vehicle_id", "V-001");

        assertThatThrownBy(() -> service.createPurchaseOrder(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldRegisterPaymentWithRequiredFields() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("purchase_order_id", "po-555");
        payload.put("payment_type", "CASH");
        payload.put("financial_institution", "Santander");

        Map<String, Object> response = service.registerPayment(payload);

        ArgumentCaptor<PaymentMethod> captor = ArgumentCaptor.forClass(PaymentMethod.class);
        verify(paymentMethodRepository).save(captor.capture());
        PaymentMethod saved = captor.getValue();

        assertThat(saved.getPurchaseOrderId()).isEqualTo("po-555");
        assertThat(saved.getPaymentType()).isEqualTo("CASH");
        assertThat(saved.getFinancialInstitution()).isEqualTo("Santander");
        assertThat(saved.getStatus()).isEqualTo("PAYMENT_CONFIGURED");

        assertThat(response).containsEntry("purchase_order_id", "po-555");
        assertThat(response).containsEntry("status", "PAYMENT_CONFIGURED");
        assertThat(response).containsEntry("payment_type", "CASH");
    }

    @Test
    void shouldThrowBadRequestWhenPurchaseOrderIdMissing() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("payment_type", "CASH");
        payload.put("financial_institution", "Santander");

        assertThatThrownBy(() -> service.registerPayment(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldThrowBadRequestWhenPaymentTypeMissing() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("purchase_order_id", "po-555");
        payload.put("financial_institution", "Santander");

        assertThatThrownBy(() -> service.registerPayment(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldThrowBadRequestWhenFinancialInstitutionMissing() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("purchase_order_id", "po-555");
        payload.put("payment_type", "CASH");

        assertThatThrownBy(() -> service.registerPayment(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldThrowBadRequestWhenRequiredFieldIsBlank() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("vehicle_id", "  ");
        payload.put("customer_id", "customer-007");

        assertThatThrownBy(() -> service.createPurchaseOrder(payload))
                .isInstanceOf(ResponseStatusException.class)
                .satisfies(ex -> assertThat(((ResponseStatusException) ex).getStatusCode())
                        .isEqualTo(HttpStatus.BAD_REQUEST));
    }

    @Test
    void shouldSavePurchaseOrderExactlyOnce() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("vehicle_id", "V-001");
        payload.put("customer_id", "customer-007");

        service.createPurchaseOrder(payload);
        verify(purchaseOrderRepository, times(1)).save(any(PurchaseOrder.class));
    }

    @Test
    void shouldSavePaymentMethodExactlyOnce() {
        Map<String, Object> payload = new HashMap<>();
        payload.put("purchase_order_id", "po-555");
        payload.put("payment_type", "CASH");
        payload.put("financial_institution", "Santander");

        service.registerPayment(payload);
        verify(paymentMethodRepository, times(1)).save(any(PaymentMethod.class));
    }
}
